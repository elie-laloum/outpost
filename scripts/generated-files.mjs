/** Names a generator's derived files and the sources contributors edit. */
export function generatedFiles({ script, outputs, sources }) {
  const command = `node scripts/${script} --write`;
  const list = new Intl.ListFormat("en", { type: "conjunction" });
  return {
    stale: (output) =>
      `${output} is stale; edit ${list.format(sources)}, then run ${command}`,
    describe: () =>
      console.log(
        `Generated by ${command}: ${list.format(outputs)}. Edit ${list.format(sources)} instead.`,
      ),
  };
}
